let embedded = null;
let embeddedReady = null;

function valuesOf(params) {
  if (params == null) return [];
  return Array.isArray(params) ? params : [params];
}

function toPostgres(sql) {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
}

function raise(error) {
  if (error?.code === "23505") {
    const duplicate = new Error(`UNIQUE ${error.detail || error.message}`);
    duplicate.code = "23505";
    throw duplicate;
  }
  throw error;
}

export async function query(db, sql, params) {
  try {
    return await db.query(toPostgres(sql), valuesOf(params));
  } catch (error) {
    raise(error);
  }
}

export async function one(db, sql, params) {
  const result = await query(db, sql, params);
  return result.rows[0] ? { ...result.rows[0] } : null;
}

export async function many(db, sql, params) {
  const result = await query(db, sql, params);
  return result.rows.map((row) => ({ ...row }));
}

export async function exec(db, sql, params) {
  const table = (sql.match(/^\s*insert\s+into\s+([a-z_]+)/i) || [])[1]?.toLowerCase();
  const hasId = new Set(["users", "leads", "activities", "notifications", "outbox", "media", "services", "steps", "articles", "gallery", "certificates", "slides", "partners", "clients", "sites", "crew", "jobs", "quotes", "invoices"]);
  const text = /^\s*insert\b/i.test(sql) && !/returning\b/i.test(sql) && hasId.has(table) ? `${sql} RETURNING id` : sql;
  const result = await query(db, text, params);
  return {
    lastInsertRowid: result.rows[0]?.id ?? null,
    changes: result.rowCount || 0,
  };
}

export async function saveMedia(db, { mime, filename, data }) {
  const result = await exec(db, "INSERT INTO media (mime, filename, data) VALUES (?, ?, ?)", [mime, filename, data]);
  return `/api/media/${result.lastInsertRowid}`;
}

export async function saveMediaFile(db, filePath) {
  const data = readFileSync(filePath);
  const ext = path.extname(filePath).toLowerCase();
  const mime = ext === ".png" ? "image/png" : ext === ".webp" ? "image/webp" : "image/jpeg";
  return saveMedia(db, { mime, filename: path.basename(filePath), data });
}

async function canConnect(database) {
  const client = new Client({
    host: "127.0.0.1",
    port: LOCAL_PORT,
    user: LOCAL_USER,
    password: LOCAL_PASSWORD,
    database,
    connectionTimeoutMillis: 800,
  });
  try {
    await client.connect();
    await client.end();
    return true;
  } catch {
    return false;
  }
}

async function ensureLocalServer() {
  if (await canConnect("postgres")) return;
  if (!embeddedReady) {
    embeddedReady = (async () => {
      embedded = new EmbeddedPostgres({
        databaseDir: path.join(dataDir, "pg"),
        user: LOCAL_USER,
        password: LOCAL_PASSWORD,
        port: LOCAL_PORT,
        persistent: true,
        onLog: () => {},
        postgresFlags: ["-c", "listen_addresses=127.0.0.1"],
      });
      try {
        await embedded.initialise();
      } catch (error) {
        const message = String(error?.message || error);
        if (!/exist|already|directory/i.test(message)) throw error;
      }
      await embedded.start();
      if (!(await canConnect("postgres"))) throw new Error("PostgreSQL did not start.");
    })();
  }
  await embeddedReady;
}

async function ensureDatabase(name) {
  if (!/^[a-z0-9_]+$/.test(name)) throw new Error("Database name is not valid.");
  const client = new Client({
    host: "127.0.0.1",
    port: LOCAL_PORT,
    user: LOCAL_USER,
    password: LOCAL_PASSWORD,
    database: "postgres",
  });
  await client.connect();
  const existing = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [name]);
  if (!existing.rowCount) await client.query(`CREATE DATABASE ${name}`);
  await client.end();
}

export async function closeDatabase(db) {
  if (db?.end) await db.end();
  if (embedded) {
    try {
      await embedded.stop();
    } catch {
      /* cluster already stopped */
    }
    embedded = null;
    embeddedReady = null;
  }
}

export async function connectAndMigrate(target) {
  const test = target === ":memory:";
  if (!test && process.env.DATABASE_URL) {
    const pool = new Pool({ connectionString: process.env.DATABASE_URL });
    await migrate(pool);
    return pool;
  }
  await ensureLocalServer();
  const database = test ? "comprehensive_cleaning_test" : process.env.PGDATABASE || "comprehensive_cleaning";
  await ensureDatabase(database);
  const pool = new Pool({
    host: "127.0.0.1",
    port: LOCAL_PORT,
    user: LOCAL_USER,
    password: LOCAL_PASSWORD,
    database,
  });
  await migrate(pool);
  if (test) {
    await pool.query(`TRUNCATE TABLE
      jobs, quotes, invoices, sites, clients, crew,
      outbox, notifications, activities, leads, sessions, users,
      slides, certificates, gallery, partners, articles, steps, pages, services, settings, media
      RESTART IDENTITY CASCADE`);
  }
  return pool;
}

async function migrate(db) {
  for (const statement of STATEMENTS) await db.query(statement);
  await db.query("ALTER TABLE articles ADD COLUMN IF NOT EXISTS image TEXT NOT NULL DEFAULT ''");
  await db.query("ALTER TABLE gallery ADD COLUMN IF NOT EXISTS category TEXT NOT NULL DEFAULT ''");
}
